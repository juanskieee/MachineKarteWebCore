$start=$teEvidence.IndexOf('Dim emCatR As New SqlCommand')
$end=$teEvidence.IndexOf('                        Dim folderPath As String', $start)
if($start -lt 0 -or $end -lt 0) { throw 'Form10 body missing' }
$body=$teEvidence.Substring($start,$end-$start)
$lines=New-Object Collections.Generic.List[string]
foreach($line in ($body -split "`r?`n")) {
    if($line -match '^\s*\x27') { continue }
    if($line -match '^\s*Dim\s+\w+\s+As\s+New SqlCommand' -or $line -match '^\s*Dim Sql As String') { continue }
    if($line -match '^\s*Dim\s+(\w+)(?:\s+As SqlDataReader)?\s*=\s*\(?\w+\.ExecuteReader\)?') {
        $line='Dim '+$Matches[1]+' As New LegacyRows(rows("'+$Matches[1]+'"))'
